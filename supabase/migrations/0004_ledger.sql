-- =============================================================================
-- 0004  The ledger. Append-only, always balanced, never edited.
-- =============================================================================
-- Two invariants are enforced here by the database itself, so that no
-- application bug and no direct SQL can violate them:
--
--   1. Every journal entry balances: SUM(debit) = SUM(credit).
--   2. A journal entry, once written, is never updated or deleted.
--      Corrections happen by writing a reversing entry.
--
-- Invariant 2 is what makes the system auditable, and it is also a legal
-- requirement once a document has been cleared by the Tax Authority.
-- =============================================================================

create table journal_entry (
  id               uuid primary key default gen_random_uuid(),
  tenant_id        uuid not null references tenant(id) on delete cascade,
  branch_id        uuid references branch(id),
  fiscal_period_id uuid not null references fiscal_period(id),

  entry_no         bigint not null,
  entry_date       date not null,
  memo_ar          text,
  memo_en          text,

  -- What caused this entry. Set for entries generated by posting a document;
  -- NULL for manual journals.
  source_doc_type  app.document_type,
  source_doc_id    uuid,

  -- Set when this entry exists to reverse another one.
  reverses_entry_id uuid references journal_entry(id),

  posted_by        uuid not null references app_user(id),
  approved_by      uuid references app_user(id),
  posted_at        timestamptz not null default now(),

  unique (tenant_id, entry_no),
  constraint journal_entry_no_self_reversal
    check (reverses_entry_id is distinct from id)
);

create index journal_entry_period_idx on journal_entry (tenant_id, fiscal_period_id);
create index journal_entry_date_idx   on journal_entry (tenant_id, entry_date);
create index journal_entry_source_idx on journal_entry (source_doc_id)
  where source_doc_id is not null;
-- An entry may only be reversed once.
create unique index journal_entry_one_reversal_idx
  on journal_entry (reverses_entry_id) where reverses_entry_id is not null;

create table journal_line (
  id             uuid primary key default gen_random_uuid(),
  entry_id       uuid not null references journal_entry(id) on delete restrict,
  tenant_id      uuid not null references tenant(id) on delete cascade,
  line_no        integer not null,

  account_id     uuid not null references account(id) on delete restrict,
  party_id       uuid,          -- FK added in 0005, once party exists
  branch_id      uuid references branch(id),

  debit          numeric(18,5) not null default 0,
  credit         numeric(18,5) not null default 0,

  -- Foreign-currency support. amount_base is always in the tenant's base
  -- currency and is what debit/credit above hold; the original is kept beside
  -- it. EGP volatility makes this worth carrying from day one.
  currency       char(3) not null default 'EGP',
  fx_rate        numeric(18,8) not null default 1,
  amount_foreign numeric(18,5),

  memo           text,

  unique (entry_id, line_no),
  constraint journal_line_non_negative check (debit >= 0 and credit >= 0),
  constraint journal_line_one_side      check ((debit = 0) <> (credit = 0)),
  constraint journal_line_fx_positive   check (fx_rate > 0)
);

comment on constraint journal_line_one_side on journal_line is
  'A line is either a debit or a credit, never both and never neither.';

create index journal_line_entry_idx   on journal_line (entry_id);
create index journal_line_account_idx on journal_line (tenant_id, account_id);
create index journal_line_party_idx   on journal_line (tenant_id, party_id)
  where party_id is not null;

-- ---------------------------------------------------------------------------
-- Invariant 1: entries balance. Deferred so that an entry can be assembled
-- line by line inside a transaction and is only judged at COMMIT.
-- ---------------------------------------------------------------------------

create or replace function app.assert_entry_balanced()
returns trigger
language plpgsql
as $$
declare
  v_entry uuid := coalesce(new.entry_id, old.entry_id);
  v_debit  numeric(18,5);
  v_credit numeric(18,5);
  v_count  integer;
begin
  select coalesce(sum(debit), 0), coalesce(sum(credit), 0), count(*)
    into v_debit, v_credit, v_count
  from journal_line
  where entry_id = v_entry;

  -- The entry was deleted wholesale inside this transaction; nothing to check.
  if v_count = 0 then
    return null;
  end if;

  if v_count < 2 then
    raise exception 'journal entry % has % line(s); at least 2 are required',
      v_entry, v_count
      using errcode = 'check_violation';
  end if;

  if v_debit <> v_credit then
    raise exception
      'journal entry % is out of balance: debit %, credit %, difference %',
      v_entry, v_debit, v_credit, (v_debit - v_credit)
      using errcode = 'check_violation';
  end if;

  return null;
end;
$$;

create constraint trigger journal_line_balanced
  after insert or update or delete on journal_line
  deferrable initially deferred
  for each row execute function app.assert_entry_balanced();

-- ---------------------------------------------------------------------------
-- Invariant 2: append-only. No UPDATE, no DELETE, ever.
-- ---------------------------------------------------------------------------

create or replace function app.refuse_mutation()
returns trigger
language plpgsql
as $$
begin
  raise exception
    '% is append-only: % is not permitted. Write a reversing entry instead.',
    tg_table_name, tg_op
    using errcode = 'restrict_violation';
end;
$$;

create trigger journal_entry_immutable
  before update or delete on journal_entry
  for each row execute function app.refuse_mutation();

create trigger journal_line_immutable
  before update or delete on journal_line
  for each row execute function app.refuse_mutation();

-- ---------------------------------------------------------------------------
-- Gap-free entry numbering. Postgres sequences leak numbers on rollback, which
-- tax authorities do not accept; a locked counter row does not.
-- ---------------------------------------------------------------------------

create table number_series (
  tenant_id   uuid not null references tenant(id) on delete cascade,
  scope       text not null,          -- 'journal' or a document_type
  year        integer not null,
  next_value  bigint not null default 1,
  prefix      text not null default '',
  primary key (tenant_id, scope, year)
);

create or replace function app.next_number(
  p_tenant uuid, p_scope text, p_year integer
)
returns bigint
language plpgsql
as $$
declare
  v_next bigint;
begin
  insert into number_series (tenant_id, scope, year, next_value)
  values (p_tenant, p_scope, p_year, 1)
  on conflict (tenant_id, scope, year) do nothing;

  -- FOR UPDATE serialises concurrent callers on this one row.
  update number_series
     set next_value = next_value + 1
   where tenant_id = p_tenant and scope = p_scope and year = p_year
  returning next_value - 1 into v_next;

  return v_next;
end;
$$;

-- ---------------------------------------------------------------------------
-- Reversal. The only sanctioned way to undo a posted entry.
-- ---------------------------------------------------------------------------

create or replace function app.reverse_entry(
  p_entry_id uuid,
  p_on       date default null,
  p_memo     text default null
)
returns uuid
language plpgsql
security definer
set search_path = public, app
as $$
declare
  v_src     journal_entry%rowtype;
  v_new_id  uuid;
  v_date    date;
  v_period  uuid;
  v_actor   uuid := app.current_user_id();
begin
  select * into v_src from journal_entry where id = p_entry_id;
  if not found then
    raise exception 'journal entry % not found', p_entry_id;
  end if;

  if exists (select 1 from journal_entry where reverses_entry_id = p_entry_id) then
    raise exception 'journal entry % has already been reversed', p_entry_id
      using errcode = 'restrict_violation';
  end if;

  -- Reverse into today's period when the original period has since closed.
  v_date   := coalesce(p_on, current_date);
  v_period := app.open_period_for(v_src.tenant_id, v_date);

  insert into journal_entry (
    tenant_id, branch_id, fiscal_period_id, entry_no, entry_date,
    memo_ar, source_doc_type, source_doc_id, reverses_entry_id, posted_by
  ) values (
    v_src.tenant_id, v_src.branch_id, v_period,
    app.next_number(v_src.tenant_id, 'journal', extract(year from v_date)::int),
    v_date,
    coalesce(p_memo, 'عكس قيد رقم ' || v_src.entry_no),
    v_src.source_doc_type, v_src.source_doc_id, v_src.id,
    coalesce(v_actor, v_src.posted_by)
  ) returning id into v_new_id;

  -- Debits become credits and credits become debits.
  insert into journal_line (
    entry_id, tenant_id, line_no, account_id, party_id, branch_id,
    debit, credit, currency, fx_rate, amount_foreign, memo
  )
  select
    v_new_id, tenant_id, line_no, account_id, party_id, branch_id,
    credit, debit, currency, fx_rate, amount_foreign, memo
  from journal_line
  where entry_id = p_entry_id;

  return v_new_id;
end;
$$;
